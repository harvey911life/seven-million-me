// 8.8.2 定存利率
export function rDepHist(y: number): number {
  if (y <= 1993) return 0.03;
  if (y <= 1994) return 0.04;
  if (y <= 1997) return 0.05;
  if (y === 1998) return 0.07;
  if (y <= 2000) return 0.05;
  if (y === 2001) return 0.025;
  if (y <= 2004) return 0.005;
  if (y === 2005) return 0.025;
  if (y <= 2007) return 0.035;
  if (y === 2008) return 0.015;
  if (y <= 2021) return 0.002;
  return ({ 2022: 0.015, 2023: 0.04, 2024: 0.035, 2025: 0.025, 2026: 0.023 } as Record<number, number>)[y] ?? 0.023;
}

// 8.11.3 按揭利率
export function rMortHist(y: number): number {
  if (y < 1993) return y >= 1979 && y <= 1982 ? 0.16 : 0.1;
  if (y <= 1997) return 0.09;
  if (y === 1998) return 0.1;
  if (y <= 2000) return 0.085;
  if (y === 2001) return 0.06;
  if (y <= 2004) return 0.028;
  if (y <= 2008) return 0.045;
  if (y <= 2022) return 0.022;
  if (y <= 2024) return 0.041;
  if (y === 2025) return 0.033;
  return 0.035;
}

